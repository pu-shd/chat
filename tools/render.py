def app_fqdn(spec: dict[str, Any], default_domain: str) -> str:
    return f"{spec['app_name']}.{default_domain}"


def reachable_url(spec: dict[str, Any], realm_slug: str, default_domain: str) -> str | None:
    """Where a realm answers right now, or None if it is not reachable before DNS."""
    realm = next((r for r in spec["realms"] if r["slug"] == realm_slug and r["active"]), None)
    if realm is None:
        return None
    if spec["dns"] == "live":
        return f"https://{realm['live_host']}/"
    if realm["preview"]:
        return f"https://{app_fqdn(spec, default_domain)}/"
    return None


def redirects_conf(spec: dict[str, Any], peers: dict[str, dict[str, Any]], default_domain: str) -> tuple[str, list[str]]:
    lines = [f"# {HEADER_NOTE}", "# chat.<dept>/<slug> -> the group's own Zulip host (Zulip cannot live under a path)."]
    skipped = []
    for r in spec["redirects"]:
        target = peers.get(r["server"])
        url = reachable_url(target, r["realm"], default_domain) if target else None
        if url is None:
            skipped.append(r["slug"])
            continue
        lines.append(f"location ~ ^/{re.escape(r['slug'])}/?$ {{ return 302 {url}; }}")
    return "\n".join(lines) + "\n", skipped


def resolve_settings(spec, peers, default_domain, oidc_client_id, acs_mail_from=None) -> tuple[dict[str, str], list[str]]:
    fqdn = app_fqdn(spec, default_domain)
    live = spec["dns"] == "live"
    conf, skipped = redirects_conf(spec, peers, default_domain)
    # host=theme for each themed host: its live name, and the pre-DNS name for the realm
    # that answers there before DNS.
    theme_pairs = []
    for t in spec.get("themes", []):
        theme_pairs.append(f"{t['host']}={t['theme']}")
        if t["preview"]:
            theme_pairs.append(f"{fqdn}={t['theme']}")
    values = {
        "themes": " ".join(dict.fromkeys(theme_pairs)),
        "acs_mail_from": acs_mail_from or "",
        "external_host": spec["external_host_live"] if live else fqdn,
        "oidc_client_id": oidc_client_id,
        "redirects_b64": base64.b64encode(conf.encode()).decode(),
    }
    if spec["kind"] == "shared":
        hosts = {r["slug"]: r["live_host"] for r in spec["realms"] if r["active"]}
        if not live:
            hosts[spec["preview_realm"]] = fqdn
        values["realm_hosts"] = pylit(hosts)
        # Pending: the OIDC callback is served on the preview host itself. Live: one
        # callback host (auth.<external_host>) for every realm, so adding a realm needs
        # no Entra change.
        values["social_auth_subdomain"] = SOCIAL_AUTH_SUBDOMAIN if live else ""
    out = {}
    for key, val in spec["settings"].items():
        def sub(m: re.Match) -> str:
            k = m.group(1)
            if k not in values:
                raise ConfigError(f"{spec['name']}: no value for placeholder {{{{{k}}}}}")
            return values[k]
        rendered = re.sub(r"\{\{([a-z0-9_]+)\}\}", sub, val)
        check_setting(spec["name"], key, rendered)
        if "{{" in rendered:
            raise ConfigError(f"{spec['name']}: unresolved placeholder left in {key}: {rendered}")
        if rendered == "":
            continue  # docker-zulip skips empty SETTING_ values; don't send them
        out[key] = rendered
    return out, skipped


# docker-zulip's entrypoint (setConfigurationValue) writes SETTING_* into settings.py.
# It strips ALL whitespace from `echo -e "$value"` and, if that is shaped like [..], (..)
# or {..}, pastes the raw value in as Python code. Only these are meant to be literals
# (render builds them with pylit()).
PYTHON_LITERAL_SETTINGS = frozenset({"SETTING_SOCIAL_AUTH_OIDC_ENABLED_IDPS", "SETTING_REALM_HOSTS"})


def check_setting(server: str, key: str, value: str) -> None:
    if re.search(r"[\x00-\x1f\x7f]", value):
        raise ConfigError(f"{server}: {key} contains a control character")
    if not key.startswith("SETTING_"):
        return
    # `echo -e` turns \x28 into "(", \c truncates, ...: no escapes at all.
    if "\\" in value:
        raise ConfigError(f"{server}: {key} contains a backslash, which docker-zulip's echo -e would interpret: {value!r}")
    if key in PYTHON_LITERAL_SETTINGS:
        return
    stripped = re.sub(r"\s", "", value)
    # Stricter than docker-zulip (which also needs the matching closer at the end):
    # nothing that is not meant to be a literal may even start like one.
    if stripped[:1] in ("(", "[", "{"):
        raise ConfigError(f"{server}: {key} would be read as Python code: {value!r}")


def cmd_resolve(args: argparse.Namespace) -> int:
    spec_path = Path(args.server)
    spec = json.loads(spec_path.read_text())
    plat = json.loads((spec_path.parent.parent / "platform.json").read_text())
    peers = {p.stem: json.loads(p.read_text()) for p in spec_path.parent.glob("*.json")}
    client_id = args.oidc_client_id or spec["entra"]["client_id"]
    if not client_id:
        raise ConfigError(f"{spec['name']}: no Entra client id (pin entra.client_id or pass --oidc-client-id)")
    if not re.fullmatch(r"[0-9a-fA-F-]{36}", client_id):
        raise ConfigError(f"{spec['name']}: '{client_id}' is not an Entra client id")
    registry = args.registry
    if not re.fullmatch(r"[a-z0-9]{5,50}\.azurecr\.io", registry or ""):
        raise ConfigError(f"--registry must be the department's <name>.azurecr.io login server, not {registry!r}")
    # Only images built into (or imported to) the department's own registry, by digest.
    if not re.fullmatch(rf"{re.escape(registry)}/chat@sha256:[0-9a-f]{{64}}", args.image or "") and not args.allow_unpinned_image:
        raise ConfigError(f"--image must be {registry}/chat@sha256:<digest> (build-image.zsh); pass --allow-unpinned-image for local tests")
    # Pulled by digest alone (<repo>@sha256:...): build-image.zsh imported exactly that
    # digest under <repo>:<tag>, and a digest reference needs no tag.
    sidecars = {}
    for k, v in json.loads((TEMPLATE_ROOT / "image" / "sidecars.json").read_text()).items():
        if k.startswith("_"):
            continue
        m = re.fullmatch(r"(?:docker\.io/)?([a-z0-9][a-z0-9._/-]*):[A-Za-z0-9._-]+@(sha256:[0-9a-f]{64})", v)
        if not m:
            raise ConfigError(f"image/sidecars.json: {k} = {v!r} is not <repo>:<tag>@sha256:<digest>")
        sidecars[k] = f"{registry}/{m.group(1)}@{m.group(2)}"
    if "{{acs_mail_from}}" in json.dumps(spec["settings"]) and not args.acs_mail_from:
        raise ConfigError(f"{spec['name']}: ACS Azure-managed domain: pass --acs-mail-from DoNotReply@<domain>")
    if args.acs_mail_from and not re.fullmatch(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+", args.acs_mail_from):
        raise ConfigError(f"--acs-mail-from {args.acs_mail_from!r} is not an address")
    settings, skipped = resolve_settings(spec, peers, args.default_domain, client_id, args.acs_mail_from)
    for slug in skipped:
        print(f"WARNING: redirect /{slug} omitted: its target is not reachable until DNS is live", file=sys.stderr)
    custom_domains = json.loads(args.custom_domains) if args.custom_domains else []
    ip_rules = json.loads(args.ip_rules) if args.ip_rules else []
    if spec["ip_gate"] and not ip_rules:
        raise ConfigError(f"{spec['name']}: ip_gate is on but no IP rules were supplied; refusing to deploy it open")
    if not spec["ip_gate"] and ip_rules:
        raise ConfigError(f"{spec['name']}: ip_gate is off but IP rules were supplied")
    params = {
        "location": plat["region"],
        "environmentName": plat["names"]["environment"],
        "appIdentityName": spec["identities"]["app"]["name"],
        "dbIdentityName": spec["identities"]["db"]["name"],
        # The -hc job's own identity (it reads only the ping key); empty without healthchecks.
        "hcIdentityName": spec["identities"].get("hc", {}).get("name", ""),
        "keyVaultName": plat["names"]["key_vault"],
        "storageAccountName": plat["names"]["storage"],
        "postgresHost": plat["postgres"]["host"],
        "postgresAdminUser": plat["postgres"]["admin_user"],
        "acaSubnet": plat["network"]["aca_subnet"],
        "tenantId": plat["tenant_id"],
        "serverName": spec["name"],
        "appName": spec["app_name"],
        "mgmtJobName": spec["jobs"]["mgmt"],
        "dbinitJobName": spec["jobs"]["dbinit"],
        "hcJobName": spec["jobs"]["hc"],
        "healthchecksEnabled": plat["healthchecks"]["enabled"],
        "healthchecksPingBase": plat["healthchecks"]["ping_base"],
        "healthchecksSlug": spec["healthchecks"]["health"],
        "healthchecksCron": f"*/{plat['healthchecks']['health_interval_minutes']} * * * *"
                            if plat["healthchecks"]["health_interval_minutes"] < 60 else "0 * * * *",
        "databaseName": spec["database"]["name"],
        "shareName": spec["share"],
        "envStorageName": spec["env_storage"],
        "dataQuotaGiB": spec["data_quota_gib"],
        # Sidecars take 0.25 vCPU / 0.5 GiB each; Zulip gets the rest.
        "zulipCpu": f"{spec['cpu'] - 0.75:g}",
        "zulipMemory": f"{spec['cpu'] * 2 - 1.5:g}Gi",
        "image": args.image,
        "registryServer": registry,
        "sidecarImages": sidecars,
        "zulipEnv": [{"name": k, "value": v} for k, v in sorted(settings.items())],
        "keyVaultSecretNames": spec["key_vault_secrets"],
        "customDomains": custom_domains,
        "ipSecurityRestrictions": ip_rules,
        "easyAuth": spec["easy_auth"],
        "easyAuthExcludedPaths": spec["easy_auth_excluded_paths"],
        "oidcClientId": client_id,
        "deployApp": args.deploy_app,
    }
    print(dump_json({
        "$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentParameters.json#",
        "contentVersion": "1.0.0.0",
        "parameters": {k: {"value": v} for k, v in params.items()},
    }), end="")
    return 0


def cmd_urls(args: argparse.Namespace) -> int:
    dept_dir = Path(args.dept_dir).resolve()
    servers_dir = dept_dir / GENERATED / "servers"
    specs = {p.stem: json.loads(p.read_text()) for p in sorted(servers_dir.glob("*.json"))}
    if not specs:
        raise ConfigError(f"{servers_dir}: nothing rendered")
    rows = []
    for name, spec in specs.items():
        for r in spec["realms"]:
            url = reachable_url(spec, r["slug"], args.default_domain)
            rows.append({
                "server": name, "realm": r["slug"] or "(root)", "dns": spec["dns"],
                "now": url or "not reachable until DNS is live",
                "live": f"https://{r['live_host']}/",
            })
    if args.json:
        print(dump_json(rows), end="")
    else:
        for row in rows:
            print(f"{row['server']:<12} {row['realm']:<20} {row['dns']:<8} now: {row['now']}  live: {row['live']}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("render")
    r.add_argument("dept_dir")
    r.add_argument("--check", action="store_true")
    r.set_defaults(func=cmd_render)
    s = sub.add_parser("resolve")
    s.add_argument("--server", required=True, help="generated/servers/<name>.json")
    s.add_argument("--default-domain", required=True, help="Container Apps environment default domain")
    s.add_argument("--image", required=True, help="<registry>/chat@sha256:... from build-image.zsh")
    s.add_argument("--registry", required=True, help="the department ACR login server, <name>.azurecr.io")
    s.add_argument("--allow-unpinned-image", action="store_true")
    s.add_argument("--oidc-client-id")
    s.add_argument("--custom-domains", help="JSON array of live customDomains to preserve")
    s.add_argument("--ip-rules", help="JSON array of ipSecurityRestrictions")
    s.add_argument("--deploy-app", type=lambda v: v.lower() == "true", default=True)
    s.add_argument("--acs-mail-from", help="DoNotReply@<Azure-managed domain> (email.acs.domain: azure-managed)")
    s.set_defaults(func=cmd_resolve)
    u = sub.add_parser("urls")
    u.add_argument("dept_dir")
    u.add_argument("--default-domain", required=True)
    u.add_argument("--json", action="store_true")
    u.set_defaults(func=cmd_urls)
    args = ap.parse_args(argv)
    try:
        return args.func(args)
    except ConfigError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
