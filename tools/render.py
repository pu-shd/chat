def write_tree(r: Rendered, out: Path) -> None:
    (out / "servers").mkdir(parents=True, exist_ok=True)
    (out / "platform.json").write_text(dump_json(r.platform))
    (out / "index.json").write_text(dump_json(r.index))
    for name, spec in r.servers.items():
        (out / "servers" / f"{name}.json").write_text(dump_json(spec))


def tree_files(root: Path) -> dict[str, str]:
    if not root.is_dir():
        return {}
    return {str(p.relative_to(root)): p.read_text() for p in sorted(root.rglob("*")) if p.is_file()}


def cmd_render(args: argparse.Namespace) -> int:
    dept_dir = Path(args.dept_dir).resolve()
    cfg = load_config(dept_dir)
    rendered = render_config(cfg, dept_dir)
    for w in rendered.warnings:
        print(f"WARNING: {w}", file=sys.stderr)
    target = dept_dir / GENERATED
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            write_tree(rendered, Path(tmp))
            want, have = tree_files(Path(tmp)), tree_files(target)
        if want == have:
            print(f"OK: {target} is up to date ({len(want)} files)")
            return 0
        for rel in sorted(set(want) | set(have)):
            if want.get(rel) != have.get(rel):
                diff = difflib.unified_diff(
                    (have.get(rel) or "").splitlines(True), (want.get(rel) or "").splitlines(True),
                    f"generated/{rel} (committed)", f"generated/{rel} (rendered)",
                )
                sys.stderr.writelines(diff)
        print(f"STALE: {target} does not match chat.yml; run tools/render.py render {args.dept_dir}", file=sys.stderr)
        return 1
    if target.exists():
        shutil.rmtree(target)
    write_tree(rendered, target)
    print(f"Rendered {len(rendered.servers)} server(s) into {target}")
    return 0


