def check_unique_names(plat: dict[str, Any], servers: dict[str, dict[str, Any]]) -> None:
    """Every name derived from server names must be unique across the department.

    Names are built by appending suffixes to <prefix>-<server>, so one server's derived
    name can equal another's (server x's x-db-id identity is server x-db's app identity;
    server a's a-mgmt job is server a-mgmt's app). Names shared on purpose by every
    server (email-password, ...) are claimed by the department and may repeat.
    """
    prefix = plat["prefix"]
    claimed: dict[tuple[str, str], str] = {}

    def claim(kind: str, value: str, owner: str) -> None:
        prev = claimed.setdefault((kind, value), owner)
        if prev != owner:
            raise ConfigError(f"{kind} name '{value}' is derived for both {prev} and {owner}; rename one of the servers")

    dept = "the department"
    claim("managed identity", plat["names"]["identity"], f"{dept} (platform identity)")
    shared_secrets = {"email-password", "pg-admin-password", HEALTHCHECKS_PING_KEY_SECRET}
    for secret in shared_secrets:
        claim("Key Vault secret", secret, f"{dept} (shared secret)")
    claim("Healthchecks slug", f"{prefix}-updates", f"{dept} (update check)")
    for name, spec in sorted(servers.items()):
        own = f"servers.{name}"
        claim("container app/job", spec["app_name"], f"{own} (app)")
        for job, jname in sorted(spec["jobs"].items()):
            claim("container app/job", jname, f"{own} ({job} job)")
        for kind, ident in sorted(spec["identities"].items()):
            claim("managed identity", ident["name"], f"{own} ({kind} identity)")
        secrets = {s for ident in spec["identities"].values() for s in ident["secrets"]}
        # Also the ones deploy/entra-app.zsh keep per server outside key_vault_secrets.
        secrets |= {*spec["key_vault_secrets"].values(), f"{name}-oidc-client-id", f"{name}-custom-domains"}
        for secret in sorted(secrets - shared_secrets):
            claim("Key Vault secret", secret, f"{own} (secret)")
        for check in ("health", "web", "ip_gate"):
            if spec["healthchecks"][check]:
                claim("Healthchecks slug", spec["healthchecks"][check], f"{own} ({check} check)")
        claim("Postgres database/role", spec["database"]["name"], f"{own} (database)")
        if spec["database"]["user"] != spec["database"]["name"]:
            claim("Postgres database/role", spec["database"]["user"], f"{own} (database user)")
        claim("storage share", spec["share"], f"{own} (share)")
        claim("environment storage", spec["env_storage"], f"{own} (environment storage)")


