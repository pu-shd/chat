def load_config(dept_dir: Path) -> dict[str, Any]:
    path = dept_dir / "chat.yml"
    if not path.is_file():
        raise ConfigError(f"{path}: not found")
    try:
        cfg = yaml.safe_load(path.read_text())
    except yaml.YAMLError as exc:
        raise ConfigError(f"{path}: invalid YAML: {exc}") from exc
    if not isinstance(cfg, dict):
        raise ConfigError(f"{path}: top level must be a mapping")
    schema = json.loads(SCHEMA_PATH.read_text())
    errors = sorted(Draft202012Validator(schema).iter_errors(cfg), key=lambda e: list(e.absolute_path))
    if errors:
        lines = []
        for err in errors:
            where = "/".join(str(p) for p in err.absolute_path) or "(root)"
            lines.append(f"  {where}: {err.message}")
        raise ConfigError(f"{path}: schema validation failed:\n" + "\n".join(lines))
    if cfg["department"] != dept_dir.name:
        raise ConfigError(
            f"{path}: department '{cfg['department']}' must match its directory name '{dept_dir.name}'"
        )
    check_strings(cfg, path)
    return cfg


def check_strings(cfg: Any, path: Path) -> None:
    """Rules the schema cannot express on every string in chat.yml (keys included).

    JSON Schema `pattern` uses Python `re.search`, where `$` also matches before a
    trailing newline, so every pattern lets a final "\\n" through. And `{{`/`}}` would be
    taken for one of resolve's placeholders.
    """
    def walk(node: Any, where: list[str]) -> None:
        if isinstance(node, dict):
            for k, v in node.items():
                walk(k, where + [f"{k} (key)"])
                walk(v, where + [str(k)])
        elif isinstance(node, list):
            for i, v in enumerate(node):
                walk(v, where + [str(i)])
        elif isinstance(node, str):
            at = "/".join(where) or "(root)"
            if re.search(r"[\x00-\x1f\x7f]", node):
                raise ConfigError(f"{path}: {at}: contains a control character (newline, tab, ...): {node!r}")
            if "{{" in node or "}}" in node:
                raise ConfigError(f"{path}: {at}: may not contain '{{{{' or '}}}}' (reserved for render placeholders): {node!r}")
    walk(cfg, [])


def available_themes() -> set[str]:
    return {p.parent.name for p in (TEMPLATE_ROOT / "image" / "themes").glob("*/theme.css")}


def check_theme(name: str | None, where: str) -> str | None:
    if name in (None, "default"):
        return None
    if name not in available_themes():
        raise ConfigError(f"{where}: theme '{name}' is not in this template (have: {', '.join(sorted(available_themes())) or 'none'})")
    return name


def is_reserved(slug: str) -> bool:
    """Mirror of zerver/lib/name_restrictions.is_reserved_subdomain (settings-free parts)."""
    if slug in (SOCIAL_AUTH_SUBDOMAIN, SYSTEM_BOT_REALM):
        return True
    for pool in (zulip_reserved.ZULIP_RESERVED_SUBDOMAINS, zulip_reserved.GENERIC_RESERVED_SUBDOMAINS):
        if slug in pool or (slug.endswith("s") and slug[:-1] in pool):
            return True
    return False


