def rate_limits_spec(cfg: dict[str, Any], gate: dict[str, Any]) -> dict[str, Any]:
    rl = {**RATE_LIMIT_DEFAULTS, **cfg.get("rate_limits", {})}
    rl["exempt_ranges"] = rl.get("exempt_ranges", gate.get("campus_ranges", DEFAULT_CAMPUS_RANGES))
    return rl


def healthchecks_base(cfg: dict[str, Any]) -> dict[str, Any]:
    hc = cfg.get("healthchecks", {})
    return {
        "enabled": bool(hc.get("enabled", False)),
        "ping_base": hc.get("ping_base", "https://hc-ping.com"),
        "api_base": hc.get("api_base", "https://healthchecks.io/api/v3"),
        "health_interval_minutes": hc.get("health_interval_minutes", 5),
        "tags": sorted(set(hc.get("tags", []) + ["chat", cfg["department"]])),
        "checks": [],
    }


def hc_check(slug: str, name: str, desc: str, timeout: int, grace: int, tags: list[str]) -> dict[str, Any]:
    return {"slug": slug, "name": name, "desc": desc, "timeout": timeout, "grace": grace, "tags": tags}


def validate_snapshot(path: Path) -> None:
    try:
        data = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as exc:
        raise ConfigError(f"{path}: unreadable pugwips snapshot: {exc}") from exc
    if not isinstance(data, dict) or not data.get("snapshot_date"):
        raise ConfigError(f"{path}: snapshot must be an object with a snapshot_date")
    if "gateways" not in data and not (data.get("prefix_mode") and data.get("prefixes")):
        raise ConfigError(f"{path}: snapshot needs either gateways{{}} (a gateways.json copy) or prefix_mode + prefixes[]")


def render_config(cfg: dict[str, Any], dept_dir: Path) -> Rendered:
    warnings: list[str] = []
    plat = platform_spec(cfg)
    prefix = plat["prefix"]
    defaults = {**SERVER_DEFAULTS, **cfg.get("defaults", {})}
    tenant = plat["tenant_id"]

    servers_cfg: dict[str, dict[str, Any]] = cfg["servers"]
    all_hosts: dict[str, str] = {}
    all_slugs: dict[str, str] = {}

    def claim_host(host: str, owner: str) -> None:
        if host in all_hosts:
            raise ConfigError(f"hostname {host} is used by both {all_hosts[host]} and {owner}")
        all_hosts[host] = owner

    def claim_slug(slug: str, owner: str) -> None:
        if slug in all_slugs:
            raise ConfigError(f"slug '{slug}' is used by both {all_slugs[slug]} and {owner}")
        if is_reserved(slug):
            raise ConfigError(f"{owner}: slug '{slug}' is reserved by Zulip; pick another")
        all_slugs[slug] = owner

    # Which dedicated server carries the chat.<dept>/<slug> redirects.
    redir_cfg = cfg.get("redirects", {})
    redirects_enabled = redir_cfg.get("enabled", True)
    host_server = redir_cfg.get("host_server")
    if redirects_enabled and host_server is None:
        roots = [n for n, s in servers_cfg.items() if s["kind"] == "dedicated" and "slug" not in s]
        if len(roots) == 1:
            host_server = roots[0]
        elif len(roots) > 1:
            raise ConfigError(
                f"several dedicated servers without a slug ({', '.join(sorted(roots))}); "
                "set redirects.host_server"
            )
        else:
            redirects_enabled = False
    if redirects_enabled:
        if host_server not in servers_cfg:
            raise ConfigError(f"redirects.host_server '{host_server}' is not a server")
        if servers_cfg[host_server]["kind"] != "dedicated":
            raise ConfigError(f"redirects.host_server '{host_server}' must be a dedicated server")

    if "from_name" in cfg["email"]:
        warnings.append("email.from_name has no effect on Zulip's mail (Zulip always sends From ZULIP_ADMINISTRATOR or "
                        "NOREPLY_EMAIL_ADDRESS and ignores DEFAULT_FROM_EMAIL); it is only the display name of ACS "
                        "sender usernames. Remove it unless that is what you want")
    if plat["acs"]:
        warnings.append("email: Microsoft retires ACS Email on 2028-09-30 and blocks new ACS customers from 2026-10-23 "
                        "(create the resource before then, or choose another provider); plan a move to Resend or M365 "
                        "High Volume Email (provider: smtp)")
        if plat["acs"]["managed"]:
            warnings.append("email: the ACS Azure-managed domain is limited to 5 mails/minute and 10/hour (not raisable); "
                            "invitations and notifications will be dropped beyond that — use it only as a stopgap")
        else:
            warnings.append("email: ACS custom domains start at 30 mails/minute and 100/hour; request an increase "
                            "(Azure support: Service and subscription limits) before a large realm goes live")
        if plat["admin_email"] != plat["email"]["from"]:
            warnings.append(f"email: Zulip sends some mail From admin_email ({plat['admin_email']}); ACS rejects senders "
                            "that are not configured on its domain, so those messages will fail")
    admin_domain = plat["admin_email"].rsplit("@", 1)[1]
    from_domain = (plat["acs"]["domain"] + ".azurecomm.net (Azure-managed)") if plat["acs"] and plat["acs"]["managed"] \
        else plat["email"]["from"].rsplit("@", 1)[1]
    if admin_domain != from_domain:
        warnings.append(
            f"admin_email is @{admin_domain} but mail is sent as @{from_domain}: Zulip sends some mail "
            f"from ZULIP_ADMINISTRATOR, so {admin_domain} must also be a verified sending domain "
            "at the mail provider, or use an admin address on the sending domain"
        )

    servers: dict[str, dict[str, Any]] = {}
    redirect_targets: list[dict[str, str]] = []
    gated_any = False

    for name in sorted(servers_cfg):
        scfg = servers_cfg[name]
        s = {**defaults, **scfg}
        app_name = f"{prefix}-{name}"
        jobs = {"mgmt": f"{app_name}-mgmt", "dbinit": f"{app_name}-dbinit", "hc": f"{app_name}-hc"}
        for n in [app_name, *jobs.values()]:
            if len(n) > ACA_NAME_MAX:
                raise ConfigError(
                    f"servers.{name}: Azure name '{n}' exceeds {ACA_NAME_MAX} characters; "
                    "shorten azure.prefix or the server name"
                )
        db = f"zulip_{name.replace('-', '_')}"
        realms: list[dict[str, Any]] = []
        hosts: list[str] = []
        server_theme = check_theme(s.get("theme"), f"servers.{name}")
        themes: list[dict[str, Any]] = []
        if s["kind"] == "dedicated":
            claim_host(s["host"], f"servers.{name}")
            check_realm_name(s["realm"]["name"], f"servers.{name}.realm")
            if server_theme:
                themes.append({"host": s["host"], "preview": True, "theme": server_theme})
            hosts.append(s["host"])
            realms.append({
                "slug": "", "name": s["realm"]["name"], "owner": s["realm"]["owner"],
                "active": True, "live_host": s["host"], "preview": True,
            })
            if "slug" in s:
                claim_slug(s["slug"], f"servers.{name}")
                redirect_targets.append({"slug": s["slug"], "server": name, "realm": ""})
            external_live = s["host"]
            preview_realm = ""
            oidc_callback_live = f"https://{s['host']}/complete/oidc/"
        else:
            ext = s["external_host"]
            auth_host = f"{SOCIAL_AUTH_SUBDOMAIN}.{ext}"
            claim_host(ext, f"servers.{name}")
            claim_host(auth_host, f"servers.{name} (OIDC callback)")
            if server_theme:
                themes += [{"host": ext, "preview": False, "theme": server_theme},
                           {"host": auth_host, "preview": False, "theme": server_theme}]
            hosts += [ext, auth_host]
            active = [r for r in s["realms"] if r.get("active", True)]
            if not active:
                raise ConfigError(f"servers.{name}: needs at least one active realm")
            preview_realm = s.get("preview_realm", active[0]["slug"])
            rd = s["realm_domain"]
            if rd != ext and rd.endswith("." + ext):
                raise ConfigError(
                    f"servers.{name}: realm_domain {rd} is under external_host {ext}; Zulip strips .{ext} from a "
                    f"request's host before it looks at REALM_HOSTS, so <slug>.{rd} would be routed to the wrong realm. "
                    f"Use realm_domain {ext} or a domain that is not under it"
                )
            for r in s["realms"]:
                where = f"servers.{name}.realms[{r['slug']}]"
                if len(r["slug"]) < REALM_SLUG_MIN:
                    raise ConfigError(f"{where}: realm slug '{r['slug']}' is too short; Zulip needs at least "
                                      f"{REALM_SLUG_MIN} characters")
                check_realm_name(r["name"], where)
                claim_slug(r["slug"], where)
                live_host = f"{r['slug']}.{s['realm_domain']}"
                is_active = r.get("active", True)
                if is_active:
                    realm_theme = check_theme(r["theme"], f"servers.{name}.realms[{r['slug']}]") if "theme" in r \
                        else server_theme
                    if realm_theme:
                        themes.append({"host": live_host, "preview": r["slug"] == preview_realm, "theme": realm_theme})
                    claim_host(live_host, f"servers.{name}.realms[{r['slug']}]")
                    hosts.append(live_host)
                    redirect_targets.append({"slug": r["slug"], "server": name, "realm": r["slug"]})
                realms.append({
                    "slug": r["slug"], "name": r["name"], "owner": r["owner"], "active": is_active,
                    "live_host": live_host, "preview": r["slug"] == preview_realm,
                })
            if preview_realm not in {r["slug"] for r in active}:
                raise ConfigError(f"servers.{name}: preview_realm '{preview_realm}' is not an active realm")
            external_live = ext
            oidc_callback_live = f"https://{auth_host}/complete/oidc/"

        if s["ip_gate"] and not plat["ip_gate"]["enabled"]:
            raise ConfigError(f"servers.{name}: ip_gate is true but ip_gate.enabled is false for the department")
        if s["ip_gate"]:
            gated_any = True
            if s["dns"] == "live" and "cert" not in s:
                raise ConfigError(
                    f"servers.{name}: ip_gate with dns: live needs cert.key_vault_certificate — "
                    "managed certificates cannot be issued or renewed while the IP gate blocks DigiCert"
                )
        if s["easy_auth"]:
            warnings.append(
                f"servers.{name}: easy_auth only guards the web UI; {', '.join(EASY_AUTH_EXCLUDED_PATHS)} "
                "stay reachable and are protected by Zulip's own login"
            )
        if s["ip_gate"] and not s["easy_auth"]:
            warnings.append(
                f"servers.{name}: ip_gate blocks the mobile apps for anyone off campus and off VPN"
            )
