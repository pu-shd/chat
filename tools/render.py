#!/usr/bin/env python3
"""render.py — turn a department's chat.yml into everything a deploy needs.

    render.py render <dept-dir> [--check]      chat.yml -> <dept-dir>/generated/
    render.py resolve --server <generated/servers/X.json> --default-domain <env domain> ...
                                              -> ARM parameters for infra/server.bicep (stdout)
    render.py urls <dept-dir> --default-domain <d>
                                              -> where every server/realm is reachable right now

`render` is pure: same chat.yml in, byte-identical files out, so `--check` can gate
CI on "generated/ is stale". Anything only known after Azure exists (the Container Apps
environment's default domain, the Entra client id when it lives in Key Vault, the
hostnames already bound, the IP rules already applied) is left as a {{placeholder}} and
filled by `resolve` at deploy time.

DNS: a server is `dns: pending` until its CNAMEs exist. While pending it is
served on its own *.azurecontainerapps.io name, which Azure already covers with TLS, so
an instance can be deployed, signed into and tested before any DNS exists. Flipping it
to `live` switches EXTERNAL_HOST (and, on a shared server, the realm hosts and the OIDC
callback host) to the real names.
"""
