class PySecret:
    """Renders as get_secret("name") inside a Python settings literal."""

    def __init__(self, name: str) -> None:
        self.name = name


def pylit(value: Any) -> str:
    """Python literal for docker-zulip SETTING_* values (dicts pass through verbatim)."""
    if isinstance(value, PySecret):
        return f"get_secret({json.dumps(value.name)})"
    if value is True:
        return "True"
    if value is False:
        return "False"
    if value is None:
        return "None"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        return "[" + ", ".join(pylit(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{json.dumps(k)}: {pylit(v)}" for k, v in sorted(value.items())) + "}"
    raise TypeError(f"no literal for {type(value)}")


def dump_json(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"


